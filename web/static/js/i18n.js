const LANGS = [
  { id: "en", label: "EN" },
  { id: "uk", label: "UA" },
  { id: "ru", label: "RU" },
];

const STORAGE_KEY = "gad.lang";
let current = localStorage.getItem(STORAGE_KEY) || "en";
if (!DICT[current]) current = "en";

export function t(key, vars) {
  const table = DICT[current] || DICT.en;
  let value = table[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}

export function lang() {
  return current;
}

export function setLang(id) {
  if (!DICT[id]) return;
  current = id;
  localStorage.setItem(STORAGE_KEY, id);
  document.documentElement.lang = id;
  document.dispatchEvent(new CustomEvent("langchange"));
}

export function languages() {
  return LANGS;
}

export function mountLangSwitch(el) {
  el.innerHTML = "";
  for (const l of LANGS) {
    const b = document.createElement("button");
    b.type = "button";
    b.textContent = l.label;
    b.className = l.id === current ? "active" : "";
    b.addEventListener("click", () => setLang(l.id));
    el.appendChild(b);
  }
}

export function translateStatic() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
}

document.documentElement.lang = current;
